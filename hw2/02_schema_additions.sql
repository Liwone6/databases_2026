-- =========================================================
-- ДЗ №2. Вариант 1: Онлайн-курсы (EdTech)
-- Часть 1. Дополнение схемы из ДЗ №1
--
-- Предполагается, что перед этим скриптом уже выполнен
-- schema.sql из ДЗ №1 (там: teacher, student, course, lesson,
-- enrollment, lesson_progress, review, payment).
--
-- Добавляются 2 новые таблицы: category и course_category.
-- Вместе они реализуют связь M:N между Course и Category
-- (у курса может быть несколько категорий, у категории —
-- несколько курсов).
-- =========================================================

DROP TABLE IF EXISTS course_category CASCADE;
DROP TABLE IF EXISTS category CASCADE;

-- ---------------------------------------------------------
-- CATEGORY: справочник категорий/тегов курса
-- (например, "Программирование", "Дизайн", "Маркетинг")
-- ---------------------------------------------------------
CREATE TABLE category (
    category_id     SERIAL PRIMARY KEY,
    name            VARCHAR(100)    NOT NULL UNIQUE,
    CONSTRAINT chk_category_name_not_blank CHECK (char_length(trim(name)) > 0)
);

-- ---------------------------------------------------------
-- COURSE_CATEGORY: ассоциативная (junction) таблица для M:N
-- между course и category.
--
-- Почему именно так, а не M:N-поле в course или category:
-- у одного курса может быть несколько категорий одновременно
-- (например, курс и "Программирование", и "Аналитика данных"),
-- и наоборот — в одной категории много курсов. Единственный
-- способ корректно смоделировать M:N в реляционной БД —
-- отдельная таблица-связка с двумя FK.
--
-- PRIMARY KEY — составной (course_id, category_id): это разом
-- и первичный ключ, и гарантия того, что одна и та же пара
-- "курс-категория" не может быть добавлена дважды (замена
-- отдельному UNIQUE-ограничению не нужна).
--
-- ON DELETE CASCADE на обоих FK — сознательный выбор:
--   - если удаляется course, его строки в course_category
--     теряют смысл (у несуществующего курса не может быть
--     категорий), поэтому они удаляются автоматически;
--   - если удаляется category, аналогично удаляются только
--     строки-связки в course_category, а сами курсы НЕ
--     удаляются — они остаются существовать, просто теряют
--     эту метку категории. Это важно: удаление тега не должно
--     "случайно" стереть курсы целиком.
-- ---------------------------------------------------------
CREATE TABLE course_category (
    course_id       INTEGER NOT NULL REFERENCES course (course_id) ON DELETE CASCADE,
    category_id     INTEGER NOT NULL REFERENCES category (category_id) ON DELETE CASCADE,
    PRIMARY KEY (course_id, category_id)
);

-- Индекс на course_id для составного PK не нужен отдельно —
-- он покрывается тем, что course_id стоит первым столбцом
-- составного первичного ключа (btree-индекс PK уже покрывает
-- поиск "все категории курса X").
-- А вот для обратного направления ("все курсы категории Y")
-- нужен отдельный индекс на category_id, иначе такой запрос
-- будет делать полный скан таблицы course_category:
CREATE INDEX idx_course_category_category_id ON course_category (category_id);

-- =========================================================
-- Дополнительные индексы к УЖЕ СУЩЕСТВУЮЩИМ таблицам из ДЗ №1,
-- которые нужны, чтобы частые запросы не делали Seq Scan.
-- =========================================================

-- Запрос "Топ-10 курсов по количеству отзывов и средней оценке":
-- GROUP BY course_id с агрегатами COUNT(*) и AVG(rating).
-- Обычного индекса на course_id (был в ДЗ №1) достаточно для
-- группировки, но покрывающий индекс, включающий rating,
-- позволяет Postgres посчитать AVG(rating) прямо по индексу,
-- не заглядывая в саму таблицу (index-only scan):
CREATE INDEX IF NOT EXISTS idx_review_course_rating ON review (course_id, rating);

-- Запрос "Сумма преподавателю за месяц": фильтр по paid_at
-- (диапазон дат) и по status = 'paid'. Индекс на enrollment_id
-- (был в ДЗ №1) хорош, когда мы идём от конкретного курса/
-- преподавателя к оплатам. Этот композитный индекс ускоряет
-- обратный путь — сразу отобрать все "paid"-платежи за период:
CREATE INDEX IF NOT EXISTS idx_payment_status_paid_at ON payment (status, paid_at);
